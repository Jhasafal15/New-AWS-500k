"""
Response Engine
AI Cloud IAM Behavioral Security System

Consumes security findings generated by the Finding Writer
and produces actionable security response recommendations.
"""

import json
import csv
from pathlib import Path

from .response_rules import (
    get_severity_rule,
    get_behavior_responses,
    get_finding_type_responses,
    get_risk_response
)


# =========================================================
# PATH CONFIGURATION
# =========================================================

import os

BASE_DIR = Path(__file__).resolve().parent.parent

INPUT_FILE = Path(os.getenv("RESPONSE_INPUT_FILE", BASE_DIR / "data" / "analyzed" / "security_findings.json"))

OUTPUT_DIR = Path(os.getenv("OUTPUT_DIR", BASE_DIR / "data" / "analyzed"))

JSON_OUTPUT = Path(os.getenv("RESPONSE_JSON", OUTPUT_DIR / "security_response_recommendations.json"))
CSV_OUTPUT = Path(os.getenv("RESPONSE_CSV", OUTPUT_DIR / "security_response_recommendations.csv"))


# =========================================================
# LOAD FINDINGS
# =========================================================

def load_findings():

    print("\nLoading security findings...")

    if not INPUT_FILE.exists():

        raise FileNotFoundError(
            f"Input file not found: {INPUT_FILE}"
        )

    with open(
        INPUT_FILE,
        "r",
        encoding="utf-8"
    ) as file:

        data = json.load(file)

    if isinstance(data, list):

        findings = data

    elif isinstance(data, dict):

        if "findings" in data:

            findings = data["findings"]

        elif "security_findings" in data:

            findings = data["security_findings"]

        elif (
            "data" in data
            and isinstance(data["data"], list)
        ):

            findings = data["data"]

        else:

            findings = [data]

    else:

        findings = []

    print(
        f"Findings loaded: {len(findings)}"
    )

    return findings


# =========================================================
# RESPONSE PRIORITY
# =========================================================

def determine_priority(
    severity,
    risk_score
):

    severity = str(
        severity
    ).upper()

    try:
        score = float(risk_score)

    except (
        TypeError,
        ValueError
    ):

        score = 0

    # Severity always provides the base priority.

    if severity == "CRITICAL":

        return "IMMEDIATE"

    if severity == "HIGH":

        return "HIGH"

    # Medium severity can become HIGH
    # when the risk score is significant.

    if severity == "MEDIUM" and score >= 60:

        return "HIGH"

    if severity == "MEDIUM":

        return "MEDIUM"

    return "LOW"


# =========================================================
# RESPONSE TYPE
# =========================================================

def determine_response_type(
    priority
):

    if priority == "IMMEDIATE":

        return "IMMEDIATE_CONTAINMENT"

    if priority == "HIGH":

        return "PRIORITY_INVESTIGATION"

    if priority == "MEDIUM":

        return "INVESTIGATION_AND_MONITORING"

    return "MONITORING"


# =========================================================
# GENERATE RESPONSE
# =========================================================

def generate_response(
    finding,
    index
):

    severity = str(
        finding.get(
            "severity",
            "LOW"
        )
    ).upper()

    event_name = finding.get(
        "event_name",
        "Unknown Event"
    )

    finding_type = finding.get(
        "finding_type",
        "Unknown Finding"
    )

    risk_score = finding.get(
        "final_risk_score",
        0
    )

    reason = finding.get(
        "reason",
        finding.get(
            "risk_reasons",
            ""
        )
    )

    # -----------------------------------------------------
    # RULE LOOKUPS
    # -----------------------------------------------------

    severity_rule = get_severity_rule(
        severity
    )

    behavior_actions = get_behavior_responses(
        reason
    )

    finding_type_actions = get_finding_type_responses(
        finding_type
    )

    risk_result = get_risk_response(
        risk_score
    )

    # -----------------------------------------------------
    # COMBINE ACTIONS
    # -----------------------------------------------------

    actions = []

    actions.extend(
        severity_rule.get(
            "actions",
            []
        )
    )

    actions.extend(
        behavior_actions
    )

    actions.extend(
        finding_type_actions
    )

    actions.extend(
        risk_result.get(
            "actions",
            []
        )
    )

    # -----------------------------------------------------
    # REMOVE DUPLICATES
    # -----------------------------------------------------

    unique_actions = []

    for action in actions:

        if action not in unique_actions:

            unique_actions.append(
                action
            )

    # -----------------------------------------------------
    # PRIORITY
    # -----------------------------------------------------

    priority = determine_priority(
        severity,
        risk_score
    )

    response_type = determine_response_type(
        priority
    )

    # -----------------------------------------------------
    # RETURN RESPONSE
    # -----------------------------------------------------

    return {

        "response_id":
            f"R-{index:04d}",

        "finding_id":
            finding.get(
                "finding_id",
                f"F-{index:04d}"
            ),

        "event_name":
            event_name,

        "finding_type":
            finding_type,

        "severity":
            severity,

        "final_risk_score":
            risk_score,

        "risk_level_from_score":
            risk_result.get(
                "risk_level",
                "LOW"
            ),

        "response_priority":
            priority,

        "response_type":
            response_type,

        "reason":
            reason,

        "recommended_action":
            severity_rule.get(
                "default_action",
                "Continue monitoring."
            ),

        "response_actions":
            unique_actions
    }


# =========================================================
# GENERATE ALL RESPONSES
# =========================================================

def generate_responses(
    findings
):

    print(
        "\nGenerating security responses..."
    )

    responses = []

    for index, finding in enumerate(
        findings,
        start=1
    ):

        response = generate_response(
            finding,
            index
        )

        responses.append(
            response
        )

    print(
        f"Security responses generated: "
        f"{len(responses)}"
    )

    return responses


# =========================================================
# SAVE JSON
# =========================================================

def save_json(
    responses
):

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    with open(
        JSON_OUTPUT,
        "w",
        encoding="utf-8"
    ) as file:

        json.dump(
            responses,
            file,
            indent=4
        )

    print(
        f"\nJSON saved to:\n{JSON_OUTPUT}"
    )


# =========================================================
# SAVE CSV
# =========================================================

def save_csv(
    responses
):

    OUTPUT_DIR.mkdir(
        parents=True,
        exist_ok=True
    )

    rows = []

    for response in responses:

        rows.append({

            "response_id":
                response["response_id"],

            "finding_id":
                response["finding_id"],

            "event_name":
                response["event_name"],

            "finding_type":
                response["finding_type"],

            "severity":
                response["severity"],

            "final_risk_score":
                response["final_risk_score"],

            "risk_level_from_score":
                response["risk_level_from_score"],

            "response_priority":
                response["response_priority"],

            "response_type":
                response["response_type"],

            "reason":
                response["reason"],

            "recommended_action":
                response["recommended_action"],

            "response_actions":
                " | ".join(
                    response["response_actions"]
                )
        })

    if not rows:

        return

    with open(
        CSV_OUTPUT,
        "w",
        newline="",
        encoding="utf-8"
    ) as file:

        writer = csv.DictWriter(
            file,
            fieldnames=rows[0].keys()
        )

        writer.writeheader()

        writer.writerows(
            rows
        )

    print(
        f"CSV saved to:\n{CSV_OUTPUT}"
    )


# =========================================================
# DISPLAY SUMMARY
# =========================================================

def display_summary(
    responses
):

    print(
        "\n" + "=" * 70
    )

    print(
        "SECURITY RESPONSE SUMMARY"
    )

    print(
        "=" * 70
    )

    print(
        f"\nTotal responses generated: "
        f"{len(responses)}"
    )

    # -----------------------------------------------------
    # Severity distribution
    # -----------------------------------------------------

    severity_counts = {}

    for response in responses:

        severity = response[
            "severity"
        ]

        severity_counts[
            severity
        ] = severity_counts.get(
            severity,
            0
        ) + 1

    print(
        "\nSeverity distribution:"
    )

    for severity in [
        "LOW",
        "MEDIUM",
        "HIGH",
        "CRITICAL"
    ]:

        print(
            f"{severity:<10}"
            f"{severity_counts.get(severity, 0)}"
        )

    # -----------------------------------------------------
    # Priority distribution
    # -----------------------------------------------------

    priority_counts = {}

    for response in responses:

        priority = response[
            "response_priority"
        ]

        priority_counts[
            priority
        ] = priority_counts.get(
            priority,
            0
        ) + 1

    print(
        "\nResponse priority distribution:"
    )

    for priority in [
        "LOW",
        "MEDIUM",
        "HIGH",
        "IMMEDIATE"
    ]:

        print(
            f"{priority:<12}"
            f"{priority_counts.get(priority, 0)}"
        )

    # -----------------------------------------------------
    # Detailed responses (Top 15 Preview)
    # -----------------------------------------------------

    preview_limit = 15
    print(
        f"\nRecommended Responses Preview (showing {min(len(responses), preview_limit)} of {len(responses)}):"
    )

    for response in responses[:preview_limit]:

        print(
            "\n" + "-" * 70
        )

        print(
            f"Response ID : "
            f"{response['response_id']}"
        )

        print(
            f"Finding     : "
            f"{response['finding_id']}"
        )

        print(
            f"Event       : "
            f"{response['event_name']}"
        )

        print(
            f"Severity    : "
            f"{response['severity']}"
        )

        print(
            f"Risk Score  : "
            f"{response['final_risk_score']}"
        )

        print(
            f"Risk Level  : "
            f"{response['risk_level_from_score']}"
        )

        print(
            f"Priority    : "
            f"{response['response_priority']}"
        )

        print(
            f"Type        : "
            f"{response['response_type']}"
        )

        print(
            f"Action      : "
            f"{response['recommended_action']}"
        )

        print(
            "Detailed actions:"
        )

        for action in response[
            "response_actions"
        ]:

            print(
                f"  - {action}"
            )


